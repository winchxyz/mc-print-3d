# ======================================================================================
# geometry containers (what the rasterizer consumes)
# ======================================================================================
@dataclass
class MobBox:
    origin: tuple[float, float, float]          # addBox x, y, z (part-relative, y down)
    size: tuple[float, float, float]            # w, h, d
    uv: tuple[float, float] = (0.0, 0.0)        # texOffs
    mirror: bool = False
    inflate: float = 0.0                        # CubeDeformation
    texture: Optional[str] = None               # override the model texture
    tint: Optional[tuple[int, int, int]] = None  # multiply (wool, slime...)
    translucent: bool = False                   # printed as the 'clear filament' color
    overlay_uv: Optional[tuple[float, float]] = None   # second skin layer baked where opaque
    overlay_texture: Optional[str] = None       # e.g. enderman eyes
    face_textures: Optional[dict] = None        # face -> (block texture resource, pixel rect or None): pumpkin heads


@dataclass
class MobPart:
    name: str
    boxes: list[MobBox] = field(default_factory=list)
    offset: tuple[float, float, float] = (0.0, 0.0, 0.0)
    rotation: tuple[float, float, float] = (0.0, 0.0, 0.0)   # radians x, y, z (PartPose)
    parent: Optional[str] = None


@dataclass
class MobModel:
    id: str
    texture: str
    parts: list[MobPart]
    scale: float = 1.0                          # renderer scale (ghast 4.5, wither skeleton 1.2, slime size...)
    tex_size: tuple[int, int] = (64, 32)        # texture size the model was authored for (HD packs scale up)
    label: str = ""
    width: float = 1.0                          # hitbox width in blocks (informational)
    height: float = 1.0
    layer: str = ""

    def part(self, name: str) -> MobPart:
        for p in self.parts:
            if p.name == name:
                return p
        raise KeyError(name)


def _box(x, y, z, w, h, d, u=0, v=0, **kw) -> MobBox:
    return MobBox((float(x), float(y), float(z)), (float(w), float(h), float(d)), (float(u), float(v)), **kw)


def _part(name, boxes, offset=(0, 0, 0), rotation=(0, 0, 0), parent=None) -> MobPart:
    return MobPart(name, list(boxes), tuple(float(v) for v in offset), tuple(float(v) for v in rotation), parent)


# ======================================================================================
# the extracted layer definitions
# ======================================================================================
_DATA_PATH = Path(__file__).with_name("vanilla_models.json")


@lru_cache(maxsize=1)
def vanilla_layers() -> dict:
    """{layer name: {'texture_size': [w, h], 'root_scale': s, 'parts': [...]}} from vanilla_models.json."""
    with open(_DATA_PATH, encoding="utf-8") as fh:
        data = json.load(fh)
    return data.get("layers", {})


OVERLAY_PART_NAMES = {"hat", "jacket", "right_sleeve", "left_sleeve", "right_pants", "left_pants", "hat_rim"}


def _layer_parts(layer: dict, *, prefix: str = "", texture: Optional[str] = None, tint=None, translucent: bool = False,
                 hidden: tuple = (), poses: Optional[dict] = None, overlays: Optional[dict] = None) -> list[MobPart]:
    """Convert one extracted layer into MobParts (hidden parts dropped, overlay layers baked)."""
    poses = poses or {}
    overlays = overlays or {}
    by_path: dict[str, MobPart] = {}
    out: list[MobPart] = []
    hidden_paths: set[str] = set()
    for p in layer["parts"]:
        path = p["path"]
        name = path.rsplit("/", 1)[-1]
        parent = p["parent"]
        if name in hidden or path in hidden or (parent and any(parent == h or parent.startswith(h + "/") for h in hidden_paths)):
            hidden_paths.add(path)
            continue
        cubes = p["cubes"]
        # overlay layer (hat / jacket / sleeves / pants): a cube of the parent's size drawn inflated over it.
        # Bake it onto that cube (or drop it when it is an inner layer); anything else named 'hat' (a witch's
        # pointed hat, a villager's brim) is real geometry and stays.
        if name in OVERLAY_PART_NAMES and parent and parent in by_path:
            host = by_path[parent]
            matched = 0
            for c in cubes:
                infl = max(c["inflate"])
                for hb in host.boxes:
                    if tuple(hb.size) == tuple(c["size"]) and tuple(hb.origin) == tuple(c["origin"]):
                        matched += 1
                        if infl > 0:
                            hb.overlay_uv = (c["uv"][0], c["uv"][1])
                            if texture:
                                hb.overlay_texture = texture
            if matched == len(cubes) and cubes:
                by_path[path] = host          # children of the overlay (a villager's hat rim) hang off the host
                continue
        rot = tuple(p["rotation"])
        if path in poses:
            rot = tuple(float(v) for v in poses[path])
        elif name in poses:
            rot = tuple(float(v) for v in poses[name])
        boxes = []
        for c in cubes:
            infl = c["inflate"]
            boxes.append(MobBox(tuple(c["origin"]), tuple(c["size"]), (c["uv"][0], c["uv"][1]), bool(c["mirror"]),
                               float(max(infl)) if max(infl) >= 0 else float(min(infl)), texture=texture, tint=tint,
                               translucent=translucent))
        for b in boxes:
            ov = overlays.get(path) or overlays.get(name)
            if ov:
                b.overlay_uv = tuple(b.uv)
                b.overlay_texture = ov
        parent_name = by_path[parent].name if parent and parent in by_path else None   # baked overlays resolve to their host
        part = MobPart(prefix + path, boxes, tuple(p["offset"]), rot, parent_name)
        by_path[path] = part
        out.append(part)
    return out


