_MUSHROOM_TEX = "minecraft:block/red_mushroom"
_CAP_RECT = (5, 4, 11, 8)
_STEM_RECT = (7, 10, 9, 14)


def _mushroom(name: str, base, parent: Optional[str] = None) -> MobPart:
    """A red mushroom standing on ``base`` (model space): 2x5x2 stem under a 6x4x6 cap (solid, unlike the
    game's crossed cut-out planes, which are one voxel thin and slice through the head)."""
    faces = ("top", "bottom", "north", "south", "west", "east")
    cap = {f: (_MUSHROOM_TEX, _CAP_RECT) for f in faces}
    stem = {f: (_MUSHROOM_TEX, _STEM_RECT) for f in faces}
    return _part(name, [_box(-1, -5, -1, 2, 5, 2, 0, 0, face_textures=stem), _box(-3, -9, -3, 6, 4, 6, 0, 0, face_textures=cap)], base, (0, 0, 0), parent)


def _apply_extras(mid: str, model: MobModel, props: dict) -> None:
    if mid == "snow_golem":
        # SnowGolemHeadLayer: carved pumpkin block scaled 0.625 (10 units) around the snow head
        model.parts.append(_part("pumpkin", [_box(-5, -5, -5, 10, 10, 10, 0, 0, face_textures=_PUMPKIN)], (0, -1.5, 0)))
    elif mid == "mooshroom":
        # MushroomCowMushroomLayer: two mushrooms on the back, one on the head
        model.parts.append(_mushroom("back_mushroom_1", (3.2, 2.0, 7.0)))
        model.parts.append(_mushroom("back_mushroom_2", (-2.5, 2.0, -1.0)))
        model.parts.append(_mushroom("head_mushroom", (0.0, -4.0, -3.0), parent="head"))


