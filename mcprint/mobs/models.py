"""Mob geometry straight from the game.

``vanilla_models.json`` is generated by ``tools/extract_entity_models.py``, which runs the entity model
code of a client jar (``CreeperModel.createBodyLayer()`` and friends) through a small bytecode
interpreter and dumps every ``LayerDefinition``: the ``ModelPart`` tree with ``PartPose`` offsets and
rotations, each ``addBox`` with its ``texOffs``, mirror flag and ``CubeDeformation``, the texture size
the model was authored for, and the scale that ``LayerDefinitions`` applies (cave spider 0.7, wither
skeleton 1.2, ghast 4.5...).  Nothing about the shapes is written by hand here.

What this module adds is the small amount of per-mob knowledge that is not in the layer definition:
which texture the renderer uses, which layers are stacked (sheep wool, the slime's outer cube), which
parts the game hides in its default state (an armadillo's rolled-up cube, a frog's tongue) and the
few rest poses that ``setupAnim`` sets at runtime (zombie arms forward, a cat's tail).  Overlay layers
(hats, jackets, sleeves) are baked onto the body part they cover instead of being printed as
paper-thin shells.

All coordinates keep Minecraft's conventions: model units (1/16 block), **y down**, ``PartPose``
rotations in radians applied as Z·Y·X.  :mod:`mcprint.mobs.raster` reproduces the renderer's
``scale(-1, -1, 1)`` and the ``180 - yaw`` turn.
"""
