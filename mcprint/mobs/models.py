def mob_model(mob_id: str, props: Optional[dict] = None) -> Optional[MobModel]:
    """Build the model for an entity id (``minecraft:creeper``, ``Creeper``...) with optional NBT-derived
    properties: ``color`` (sheep), ``sheared``, ``size`` (slime / magma cube), ``variant`` (pig, cow,
    chicken, wolf, cat, frog, axolotl, rabbit, horse, parrot, llama, fox, shulker, panda), ``texture``
    (override resource) and ``slim`` (player)."""
    props = props or {}
    mid = normalize_mob_id(mob_id)
    if mid == "player" and props.get("slim"):
        mid = "player_slim"
    spec = REGISTRY.get(mid)
    if spec is None:
        return None
    layers = vanilla_layers()
    layer_name = spec.layer
    variant = str(props.get("variant", "")).split(":")[-1]
    if variant and (mid, variant) in _VARIANT_LAYERS and _VARIANT_LAYERS[(mid, variant)] in layers:
        layer_name = _VARIANT_LAYERS[(mid, variant)]
    layer = layers.get(layer_name)
    if layer is None:
        return None
    texture = spec.texture
    if variant and mid in _VARIANT_TEXTURES and variant in _VARIANT_TEXTURES[mid]:
        texture = _VARIANT_TEXTURES[mid][variant]
    if props.get("texture"):
        texture = str(props["texture"])
    parts = _layer_parts(layer, hidden=spec.hidden, poses=spec.poses, overlays=spec.overlays)
    scale = float(layer.get("root_scale", 1.0)) * spec.scale
    if mid in ("slime", "magma_cube"):
        scale *= float(max(1, int(props.get("size", 1)) + 1))
    model = MobModel(mid, texture, parts, scale=scale, tex_size=tuple(layer["texture_size"]), label=spec.label or mid.replace("_", " "),
                     width=spec.width * scale, height=spec.height, layer=layer_name)
    for extra_layer, extra_tex, tint, translucent in spec.extra_layers:
        if mid == "sheep":
            if props.get("sheared"):
                continue
            color = props.get("color", "white")
            if isinstance(color, int) or (isinstance(color, str) and color.isdigit()):
                color = DYE_NAMES[int(color) % 16]
            tint = DYE_RGB.get(str(color), DYE_RGB["white"])
        lay = layers.get(extra_layer)
        if lay is None:
            continue
        extra_parts = _layer_parts(lay, prefix=extra_layer + ":", texture=extra_tex, tint=tint, translucent=translucent)
        if translucent:
            model.parts[:0] = extra_parts        # stamped first so the opaque core and eyes stay visible inside the shell
        else:
            model.parts.extend(extra_parts)
    _apply_extras(mid, model, props)
    return model


